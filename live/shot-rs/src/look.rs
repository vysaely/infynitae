use std::env;
use std::fs;
use std::path::PathBuf;

/// RGBA color encoded as normalised floating-point channels for Cairo.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Color {
    pub r: f64,
    pub g: f64,
    pub b: f64,
    pub a: f64,
}

impl Color {
    pub const fn rgba8(r: u8, g: u8, b: u8, a: u8) -> Self {
        Self {
            r: r as f64 / 255.0,
            g: g as f64 / 255.0,
            b: b as f64 / 255.0,
            a: a as f64 / 255.0,
        }
    }

    pub const fn rgb8(r: u8, g: u8, b: u8) -> Self {
        Self::rgba8(r, g, b, 255)
    }

    pub fn set_source_with_alpha(self, cr: &cairo::Context, alpha: f64) {
        cr.set_source_rgba(self.r, self.g, self.b, self.a * alpha);
    }
}

/// Visual tokens loaded from `~/.cache/infynitae/look`, falling back to the edge's defaults.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Look {
    pub card: Color,
    pub edge: Color,
    pub text: Color,
    pub accent: Color,
    pub corners: u32,
}

impl Default for Look {
    fn default() -> Self {
        Self {
            card: Color::rgb8(0x11, 0x13, 0x17),
            edge: Color::rgb8(0x33, 0x3b, 0x54),
            text: Color::rgb8(0xee, 0xf2, 0xf8),
            accent: Color::rgb8(0x7a, 0xa2, 0xf7),
            corners: 8,
        }
    }
}

impl Look {
    /// Loads the look file from `$XDG_CACHE_HOME/infynitae/look` or `$HOME/.cache/infynitae/look`.
    /// Missing files or malformed lines keep the edge defaults.
    pub fn load() -> Self {
        let Some(path) = look_path() else {
            return Self::default();
        };
        let Ok(content) = fs::read_to_string(path) else {
            return Self::default();
        };
        Self::parse(&content)
    }

    pub fn parse(content: &str) -> Self {
        let mut look = Self::default();
        for raw_line in content.lines() {
            let line = raw_line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let Some((key, raw_val)) = line.split_once('=') else {
                continue;
            };
            let key = key.trim();
            let val = strip_quotes(raw_val.trim());
            match key {
                "LOOK_CARD" => {
                    if let Some(c) = parse_hex_color(val) {
                        look.card = c;
                    }
                }
                "LOOK_EDGE" => {
                    if let Some(c) = parse_hex_color(val) {
                        look.edge = c;
                    }
                }
                "LOOK_TEXT" => {
                    if let Some(c) = parse_hex_color(val) {
                        look.text = c;
                    }
                }
                "LOOK_ACCENT" => {
                    if let Some(c) = parse_hex_color(val) {
                        look.accent = c;
                    }
                }
                "LOOK_CORNERS" => {
                    if let Ok(n) = val.parse::<u32>() {
                        look.corners = n;
                    }
                }
                _ => {}
            }
        }
        look
    }
}

fn look_path() -> Option<PathBuf> {
    if let Some(xdg) = env::var_os("XDG_CACHE_HOME").filter(|s| !s.is_empty()) {
        return Some(PathBuf::from(xdg).join("infynitae/look"));
    }
    env::var_os("HOME")
        .filter(|s| !s.is_empty())
        .map(|h| PathBuf::from(h).join(".cache/infynitae/look"))
}

fn strip_quotes(s: &str) -> &str {
    if s.len() >= 2
        && ((s.starts_with('"') && s.ends_with('"')) || (s.starts_with('\'') && s.ends_with('\'')))
    {
        &s[1..s.len() - 1]
    } else {
        s
    }
}

/// Parses `#RRGGBB` or `#RRGGBBAA` hex colours.
pub fn parse_hex_color(s: &str) -> Option<Color> {
    let hex = s.strip_prefix('#')?;
    let r = u8::from_str_radix(hex.get(0..2)?, 16).ok()?;
    let g = u8::from_str_radix(hex.get(2..4)?, 16).ok()?;
    let b = u8::from_str_radix(hex.get(4..6)?, 16).ok()?;
    match hex.len() {
        6 => Some(Color::rgb8(r, g, b)),
        8 => {
            let a = u8::from_str_radix(hex.get(6..8)?, 16).ok()?;
            Some(Color::rgba8(r, g, b, a))
        }
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn missing_look_uses_defaults() {
        let parsed = Look::parse("");
        assert_eq!(parsed, Look::default());
    }

    #[test]
    fn parses_valid_and_ignores_invalid_lines() {
        let input = r##"
# generated by settings
LOOK_CARD="#1e2030"
LOOK_EDGE=not-a-color
LOOK_TEXT="#c0caf580"
LOOK_ACCENT='#ff9e64'
LOOK_CORNERS="notanumber"
NO_EQUALS_HERE
LOOK_UNRELATED="#000000"
LOOK_EDGE="#292e42"
LOOK_CORNERS="12"
"##;
        let parsed = Look::parse(input);
        assert_eq!(parsed.card, Color::rgb8(0x1e, 0x20, 0x30));
        assert_eq!(parsed.edge, Color::rgb8(0x29, 0x2e, 0x42));
        assert_eq!(parsed.text, Color::rgba8(0xc0, 0xca, 0xf5, 0x80));
        assert_eq!(parsed.accent, Color::rgb8(0xff, 0x9e, 0x64));
        assert_eq!(parsed.corners, 12);
    }

    #[test]
    fn invalid_hex_preserves_defaults() {
        let input = r##"
LOOK_CARD="#12345"
LOOK_EDGE="#gggggg"
LOOK_TEXT="ff0000"
LOOK_ACCENT="#123456789"
LOOK_CORNERS="-5"
"##;
        let parsed = Look::parse(input);
        assert_eq!(parsed, Look::default());
    }
}
